import type { CoverInfo } from "./covers.js";

/**
 * Generate Home Assistant YAML: rest_command + modern template covers.
 * Paste into configuration.yaml (or !include). No MQTT required.
 *
 * Only covers with open+close are emitted as entities; incomplete ones
 * are listed as comments (HA requires both open_cover and close_cover).
 */
export function generateHaYaml(
  covers: CoverInfo[],
  baseUrl: string,
): string {
  const base = baseUrl.replace(/\/$/, "");
  const ready = covers.filter((c) => c.ready);
  const incomplete = covers.filter((c) => !c.ready);

  const lines: string[] = [
    "# Generated by Nodi — Home Assistant cover bridge",
    `# Base URL: ${base}`,
    "# After paste: Developer Tools → YAML → check config → reload REST + Template",
    "# (or restart HA). Keep `npm run cli -- serve` running on the Mac.",
    "",
  ];

  if (incomplete.length > 0) {
    lines.push("# Incomplete (need open+close before HA entity):");
    for (const c of incomplete) {
      lines.push(
        `#   ${c.id} (${c.name}) — have: ${c.actions.join(",") || "none"}`,
      );
    }
    lines.push("");
  }

  if (ready.length === 0) {
    lines.push("# No ready covers — learn up AND down for at least one shutter.");
    lines.push("");
    return lines.join("\n");
  }

  lines.push("rest_command:");
  for (const c of ready) {
    for (const action of c.actions) {
      lines.push(`  ${restKey(c.id, action)}:`);
      lines.push(
        `    url: "${base}/api/covers/${encodeURIComponent(c.id)}/${action}"`,
      );
      lines.push(`    method: POST`);
    }
  }

  lines.push("");
  lines.push("template:");
  lines.push("  - cover:");

  for (const c of ready) {
    const uid = entityId(c.id);
    lines.push(`      - name: ${yamlString(c.name)}`);
    lines.push(`        unique_id: ${uid}`);
    lines.push(`        device_class: shutter`);
    // No state/position → HA optimistic mode (IR/RF has no feedback).
    lines.push(`        open_cover:`);
    lines.push(`          - action: rest_command.${restKey(c.id, "open")}`);
    lines.push(`        close_cover:`);
    lines.push(`          - action: rest_command.${restKey(c.id, "close")}`);
    if (c.actions.includes("stop")) {
      lines.push(`        stop_cover:`);
      lines.push(`          - action: rest_command.${restKey(c.id, "stop")}`);
    }
  }

  lines.push("");
  return lines.join("\n");
}

/** Stable HA unique_id / rest_command prefix. */
export function entityId(shutterId: string): string {
  const safe = shutterId
    .toLowerCase()
    .replace(/[^a-z0-9_]+/g, "_")
    .replace(/^_|_$/g, "");
  return `nodi_${safe || "cover"}`;
}

export function restKey(shutterId: string, action: string): string {
  return `${entityId(shutterId)}_${action}`;
}

function yamlString(value: string): string {
  if (/^[\w äöüÄÖÜß\-]+$/u.test(value)) return `"${value}"`;
  return JSON.stringify(value);
}
